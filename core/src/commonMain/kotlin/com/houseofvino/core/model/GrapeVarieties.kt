/**
 * A wine grape variety. [name] is the internationally most common spelling; [synonyms] are other
 * names it is sold under. Neither contains a character the grape parser splits on or reads as a
 * percentage (, ; / | + % and parentheses), so a name can always be written into the grapes field.
 * Pink- and grey-skinned grapes made into white wine (Pinot Gris, Gewürztraminer) are [WineColor.WHITE].
 */
data class GrapeVariety(val name: String, val color: WineColor, val synonyms: List<String> = emptyList())

private fun r(name: String, vararg synonyms: String) = GrapeVariety(name, WineColor.RED, synonyms.toList())
private fun w(name: String, vararg synonyms: String) = GrapeVariety(name, WineColor.WHITE, synonyms.toList())

