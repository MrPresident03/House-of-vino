    /** The most widely planted and bought varieties, in a sensible order (reds, then whites). */
    val common: List<GrapeVariety> by lazy {
        listOf(
            "Cabernet Sauvignon", "Merlot", "Pinot Noir", "Syrah", "Grenache", "Tempranillo", "Sangiovese", "Nebbiolo",
            "Malbec", "Zinfandel", "Cabernet Franc", "Mourvèdre", "Barbera", "Gamay", "Montepulciano", "Carménère", "Pinotage",
            "Chardonnay", "Sauvignon Blanc", "Riesling", "Pinot Gris", "Chenin Blanc", "Sémillon", "Viognier", "Gewürztraminer",
            "Albariño", "Grüner Veltliner", "Pinot Blanc", "Muscat Blanc à Petits Grains", "Glera", "Verdejo", "Vermentino", "Trebbiano",
        ).mapNotNull { find(it) }
    }

    private class Keyed(val variety: GrapeVariety, val name: String, val synonyms: List<String>)

    private val keyed: List<Keyed> by lazy {
        all.map { v -> Keyed(v, TextNormalizer.normalize(v.name), v.synonyms.map { TextNormalizer.normalize(it) }) }
    }

    private val index: Map<String, GrapeVariety> by lazy {
        buildMap {
            for (k in keyed) {
                // First one wins. (No putIfAbsent: it's JVM-only and this is common code.)
                if (k.name !in this) put(k.name, k.variety)
                k.synonyms.forEach { if (it !in this) put(it, k.variety) }
            }
        }
    }

    /** Finds a variety by canonical name or synonym, ignoring case and accents. */
    fun find(name: String): GrapeVariety? {
        val key = TextNormalizer.normalize(name)
        return if (key.isEmpty()) null else index[key]
    }

    /**
     * Varieties whose name or synonym starts with, or contains, [query] (accent- and case-insensitive).
     * Name prefix matches come first, then other name matches, then synonym matches. A blank query returns [all].
     */
    fun search(query: String, limit: Int = 60): List<GrapeVariety> {
        val q = TextNormalizer.normalize(query)
        if (q.isEmpty()) return all
        val scored = ArrayList<Pair<Int, GrapeVariety>>()
        for (k in keyed) {
            val rank = when {
                k.name.startsWith(q) -> 0
                k.name.contains(" $q") -> 1
                k.name.contains(q) -> 2
                k.synonyms.any { it.startsWith(q) || it.contains(" $q") } -> 3
                k.synonyms.any { it.contains(q) } -> 4
                else -> continue
            }
            scored += rank to k.variety
        }
        // sortedBy is stable, so equal ranks keep A-Z order.
        return scored.sortedBy { it.first }.map { it.second }.take(limit)
    }
