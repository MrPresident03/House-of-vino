    private fun rows(q: QrCode) = (0 until q.size).map { r -> (0 until q.size).joinToString("") { c -> if (q[r, c]) "1" else "0" } }

    @Test fun matchesTheReferenceEncoderBitForBit() {
        for ((input, version, expected) in references) {
            val (text, ecc, mask) = input
            val q = QrCode.encode(text, ecc, mask)
            assertEquals(version, q.version, text)
            assertEquals(expected, rows(q), text)
        }
    }

    @Test fun picksTheSmallestVersionAndAValidMask() {
        val q = QrCode.encode("HOV1-" + "a".repeat(300))
        assertEquals(17 + 4 * q.version, q.size)
        assertTrue(q.mask in 0..7)
        // Finder pattern corners are dark, separators light.
        for ((r, c) in listOf(0 to 0, 0 to q.size - 1, q.size - 1 to 0)) assertTrue(q[r, c])
        assertTrue(!q[7, 7])
    }

    @Test fun tooMuchDataIsRefused() {
        assertFailsWith<IllegalArgumentException> { QrCode.encode("x".repeat(3000), QrCode.Ecc.H) }
    }
